#!/usr/bin/env node
// Embeds @mozilla/readability's Readability.js into engine/src/browser/readability.gen.ts: fetch_page injects it into the
// page (an isolated world), so the engine needs no DOM of its own.
import fs from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';
import { fileURLToPath, pathToFileURL } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));

export function readabilitySource(resolve = createRequire(import.meta.url).resolve) {
  return fs.readFileSync(resolve('@mozilla/readability/Readability.js'), 'utf8');
}

export function renderModule(source) {
  return `// Generated by engine/scripts/embed-readability.mjs from @mozilla/readability (Apache-2.0). Do not edit.\nexport const READABILITY_JS: string = ${JSON.stringify(source)};\n`;
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? '').href) {
  const out = path.join(here, '..', 'src', 'browser', 'readability.gen.ts');
  fs.writeFileSync(out, renderModule(readabilitySource()));
}
