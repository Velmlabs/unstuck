#!/usr/bin/env node
// Embeds viewer/dist into engine/src/assets.gen.ts so the engine binary is a single file.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const MIME = {
  '.html': 'text/html; charset=utf-8',
  '.js': 'text/javascript; charset=utf-8',
  '.css': 'text/css; charset=utf-8',
  '.svg': 'image/svg+xml',
  '.png': 'image/png',
  '.ico': 'image/x-icon',
  '.webmanifest': 'application/manifest+json',
  '.json': 'application/json',
};

export function buildAssetMap(distDir) {
  if (!fs.existsSync(path.join(distDir, 'index.html'))) {
    throw new Error(`viewer build not found at ${distDir}; run: pnpm --filter @unstuck/viewer build`);
  }
  const map = {};
  const walk = (dir) => {
    for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
      const full = path.join(dir, e.name);
      if (e.isDirectory()) walk(full);
      else {
        const rel = '/' + path.relative(distDir, full).split(path.sep).join('/');
        map[rel] = { type: MIME[path.extname(e.name)] ?? 'application/octet-stream', body: fs.readFileSync(full).toString('base64') };
      }
    }
  };
  walk(distDir);
  return map;
}

export function renderModule(map) {
  return `// Generated by engine/scripts/embed-viewer.mjs. Do not edit.\nimport type { AssetMap } from './embedded';\nexport const ASSETS: AssetMap = ${JSON.stringify(map, null, 1)};\n`;
}

/* v8 ignore next 7 -- CLI hand-off */
if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const here = path.dirname(fileURLToPath(import.meta.url));
  const map = buildAssetMap(path.join(here, '..', '..', 'viewer', 'dist'));
  fs.writeFileSync(path.join(here, '..', 'src', 'assets.gen.ts'), renderModule(map));
  console.log(`embedded ${Object.keys(map).length} viewer files into src/assets.gen.ts`);
}
