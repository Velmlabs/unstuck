import { describe, it, expect } from 'vitest';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
// @ts-expect-error plain .mjs build script
import { readabilitySource, renderModule } from '../scripts/embed-readability.mjs';
import { READABILITY_JS } from '../src/browser/readability.gen';

describe('embed-readability', () => {
  it('embeds Readability.js as a string module', () => {
    const src: string = readabilitySource();
    expect(src).toContain('function Readability(');
    const mod: string = renderModule(src);
    expect(mod).toMatch(/^\/\/ Generated by engine\/scripts\/embed-readability\.mjs/);
    expect(mod).toContain('export const READABILITY_JS: string = ');
    expect(READABILITY_JS).toBe(src);
  });

  it('reads the file the resolver points at', () => {
    const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'readability-'));
    const file = path.join(dir, 'Readability.js');
    fs.writeFileSync(file, 'function Readability() {}');
    expect(readabilitySource(() => file)).toBe('function Readability() {}');
    expect(renderModule('a"b\n')).toContain('"a\\"b\\n"');
  });
});
