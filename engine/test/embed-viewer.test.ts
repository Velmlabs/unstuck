import { describe, it, expect } from 'vitest';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
// @ts-expect-error plain .mjs build script
import { buildAssetMap, renderModule } from '../scripts/embed-viewer.mjs';

describe('embed-viewer', () => {
  it('maps every file under dist to a URL path with MIME type and base64 body', () => {
    const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'dist-'));
    fs.mkdirSync(path.join(dir, 'assets'));
    fs.writeFileSync(path.join(dir, 'index.html'), '<p>x</p>');
    fs.writeFileSync(path.join(dir, 'assets', 'a.js'), 'js');
    fs.writeFileSync(path.join(dir, 'assets', 'a.css'), 'css');
    fs.writeFileSync(path.join(dir, 'icon.svg'), '<svg/>');
    fs.writeFileSync(path.join(dir, 'x.bin'), 'b');
    const map = buildAssetMap(dir);
    expect(map['/index.html']).toEqual({ type: 'text/html; charset=utf-8', body: Buffer.from('<p>x</p>').toString('base64') });
    expect(map['/assets/a.js'].type).toBe('text/javascript; charset=utf-8');
    expect(map['/assets/a.css'].type).toBe('text/css; charset=utf-8');
    expect(map['/icon.svg'].type).toBe('image/svg+xml');
    expect(map['/x.bin'].type).toBe('application/octet-stream');
    expect(renderModule(map)).toMatch(/^\/\/ Generated by engine\/scripts\/embed-viewer\.mjs/);
    expect(renderModule(map)).toContain('export const ASSETS');
  });

  it('fails loudly when the viewer has not been built', () => {
    expect(() => buildAssetMap('/no/such/dist')).toThrow(/pnpm --filter @unstuck\/viewer build/);
  });
});
